async function main() {
  console.log("Limpiando Tareas derivadas de ReglaRecurrencia...");
  await prisma.tarea.deleteMany({
    where: { reglaRecurrenciaId: { not: null } }
  });

  console.log("Limpiando ReglaRecurrencia actuales...");
  await prisma.reglaRecurrencia.deleteMany({});

  const maquinas = await prisma.maquina.findMany({ select: { id: true, codigo: true, planta: true, area: true } });
  const mapMaquinas = new Map(maquinas.map((m) => [m.codigo.toUpperCase(), m]));

  const tecnicos = await prisma.usuario.findMany({ where: { rol: "TECNICO", estado: "ACTIVO" } });
  if (tecnicos.length === 0) {
    throw new Error("No hay técnicos activos en el sistema para asignar las tareas.");
  }
  let indexTecnico = 0;

  const lineas = rawData.split(/\r?\n/).map((l) => l.trim()).filter((l) => l.length > 0);
  
  let creadas = 0;
  let materializadas = 0;
  let noEncontradas = [];

  const hoy = new Date();
  hoy.setUTCHours(0,0,0,0);

  for (const linea of lineas) {
    const [codigo, fechaStr] = linea.split(/\t/).map((x) => x.trim());
    const cod = codigo === "MNC0310" ? "MBC0310" : codigo;

    const maquina = mapMaquinas.get(cod.toUpperCase());
    if (!maquina) {
      noEncontradas.push(cod);
      continue;
    }

    const [dia, mes, anio] = fechaStr.split("/");
    const proximaFechaEjecucion = new Date(Date.UTC(Number(anio), Number(mes) - 1, Number(dia), 12, 0, 0));

    const tecnicoResponsableId = tecnicos[indexTecnico % tecnicos.length].id;
    indexTecnico++;

    const regla = await prisma.reglaRecurrencia.create({
      data: {
        maquinaId: maquina.id,
        titulo: "Mantenimiento Preventivo Programado",
        descripcion: "Generación mensual automática",
        categoria: "MAQUINARIA",
        prioridad: Prioridad.MEDIA,
        frecuencia: FrecuenciaRecurrencia.MENSUAL,
        tecnicoResponsableId,
        proximaFechaEjecucion,
        activo: true,
      },
    });
    creadas++;

    if (proximaFechaEjecucion.getTime() <= hoy.getTime()) {
      try {
        await prisma.tarea.create({
          data: {
            titulo: "Mantenimiento Preventivo Programado",
            descripcion: "Generación mensual automática",
            maquinaId: maquina.id,
            tipo: "PLANEADA",
            estado: EstadoTarea.ASIGNADA,
            clasificacion: ClasificacionTarea.PREVENTIVO,
            prioridad: Prioridad.MEDIA,
            creadorId: tecnicoResponsableId,
            responsables: { connect: [{ id: tecnicoResponsableId }] },
            planta: maquina.planta || "Desconocida",
            area: maquina.area || "Desconocida",
            reglaRecurrenciaId: regla.id,
            fechaVencimiento: proximaFechaEjecucion,
            fechaProgramadaPreventiva: proximaFechaEjecucion,
            fechaCicloLogica: proximaFechaEjecucion,
          }
        });
        materializadas++;
        
        // Mover la fecha de la regla un mes adelante para el próximo ciclo
        const sig = new Date(proximaFechaEjecucion);
        sig.setUTCMonth(sig.getUTCMonth() + 1);
        await prisma.reglaRecurrencia.update({
          where: { id: regla.id },
          data: { proximaFechaEjecucion: sig }
        });
      } catch (err) {
        console.error("Error al materializar regla " + regla.id, err);
      }
    }
  }

  console.log("Proceso completado. Reglas creadas: " + creadas);
  console.log("Tickets atrasados/actuales materializados: " + materializadas);
  if (noEncontradas.length > 0) {
    console.log("No encontradas en BD:", noEncontradas);
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
